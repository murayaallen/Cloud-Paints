/* Pull the FAQ straight out of the page. Writing the questions a second time
   here would let the two drift, and a mismatch between the markup and what
   the page says is exactly what Google penalises. */
function faqFromPage(html) {
  const items = [];
  const re = /<button[^>]*class="ct-faq-q"[\s\S]*?<span>([\s\S]*?)<\/span>[\s\S]*?<div class="ct-faq-a-inner">([\s\S]*?)<\/div>/g;
  let m;
  while ((m = re.exec(html))) {
    const q = decode(m[1]);
    const a = decode(m[2]);
    if (q && a) items.push({
      '@type': 'Question',
      name: q,
      acceptedAnswer: { '@type': 'Answer', text: a },
    });
  }
  return items.length ? { '@type': 'FAQPage', mainEntity: items } : null;
}

