// ============================================================
// CLOUD PAINTS — structured data
// ============================================================
//   node build/schema.mjs
//
// Writes the JSON-LD every page needs into the page itself,
// between two markers, so a re-run replaces rather than stacks.
//
// What this is for. Google decides on its own what to show under
// a result — the extra links, the address panel, the FAQ rows. It
// decides from the page, and structured data is the part of the
// page written for it rather than for a reader: who the company
// is, where it is, what the catalogue contains, which page sits
// under which. None of it is a promise of a rich result. All of
// it is the difference between Google inferring and Google being
// told.
//
// Nothing here invents a fact. Every value is read from
// js/products-data.js, from the page's own copy, or from the one
// company block below.
// ============================================================

