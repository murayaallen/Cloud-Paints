/* ---------- write it in -------------------------------------------------- */
let touched = 0;
const summary = [];

for (const file of fs.readdirSync(ROOT).filter(f => f.endsWith('.html'))) {
  const full = path.join(ROOT, file);
  let html = fs.readFileSync(full, 'utf8');

  // Drop any previous block first, so this is a replace and never a stack.
  const between = new RegExp(START.replace(/[.*+?^${}()|[\]\\—]/g, '\\$&')
    + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?', 'g');
  html = html.replace(between, '');

  const graph = graphFor(file, html);
  if (!graph) { fs.writeFileSync(full, html, 'utf8'); continue; }

  const doc = { '@context': 'https://schema.org', '@graph': graph };
  const block = `${START}\n<script type="application/ld+json">\n`
    + JSON.stringify(doc, null, 1) + `\n</script>\n${END}\n`;

  html = html.replace('</head>', block + '</head>');
  fs.writeFileSync(full, html, 'utf8');
  touched++;
  summary.push(`  ${file.replace('.html', '').padEnd(28)} ${graph.map(g =>
    Array.isArray(g['@type']) ? g['@type'].join('+') : g['@type']).join(', ')}`);
}

