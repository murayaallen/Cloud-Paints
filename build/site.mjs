// ============================================================
// CLOUD PAINTS — site build
// ============================================================
// Three generated artefacts, all driven by js/products-data.js
// and by what is actually on disk:
//
//   js/art-manifest.js   what photograph each product really has
//   paints/<slug>.html   28 real product URLs, one per product
//   sitemap.xml          every canonical URL, dated from git
//
//   node build/site.mjs
//
// Nothing here is hand-maintained. Change a product on the site
// and re-run this; print, web and search all follow.
// ============================================================

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ORIGIN = 'https://cloudpaints.co.ke';

const CO = {
  brand: 'Cloud Paints',
  legal: 'Cloudsent Decor Ltd',
  street: '10 Rangwe Road, off Lunga Lunga Road',
  area: 'Industrial Area',
  city: 'Nairobi',
  country: 'KE',
  postal: '00100',
  phones: ['+254741405481', '+254788866620', '+254727779085'],
  email: 'info@cloudpaints.co.ke',
  sameAs: [
    'https://www.facebook.com/cloudpaintsKE',
    'https://www.instagram.com/cloudpaints',
  ],
};

/* ---------- catalogue ---------------------------------------------------- */
function loadProducts() {
  const src = fs.readFileSync(path.join(ROOT, 'js', 'products-data.js'), 'utf8');
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(src, ctx, { filename: 'products-data.js' });
  return ctx.window.CLOUD_PRODUCTS;
}
const P = loadProducts();

const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/* Meta descriptions are cut to fit the search result rather than the page.
   Google shows about 155–160 characters on desktop and less on a phone;
   anything past that is replaced with an ellipsis it chose, not one we did.
   Cut on a sentence if there is one in range, otherwise on a word. */
function metaDescription(text, max = 155) {
  const t = String(text || '').replace(/\s+/g, ' ').trim();
  if (t.length <= max) return t;
  const window_ = t.slice(0, max + 1);
  const stop = Math.max(window_.lastIndexOf('. '), window_.lastIndexOf('! '), window_.lastIndexOf('? '));
  if (stop > max * 0.55) return t.slice(0, stop + 1).trim();
  return window_.slice(0, window_.lastIndexOf(' ')).replace(/[,;:—-]$/, '').trim() + '…';
}

/* ---------- 1. art manifest ---------------------------------------------
   The product page used to guess: ask for the cut-out, fall back to the flat
   photograph, fall back again to a typographic panel. Only twelve of the
   twenty-eight products have a cut-out and four have no photograph at all,
   so that guess cost up to two 404s on most product pages. Resolve it here,
   once, against the filesystem. */
const has = rel => fs.existsSync(path.join(ROOT, rel));

const ART = {};
const noArt = [];
for (const p of P) {
  const candidates = [
    `images/buckets/hero/${p.slug}.png`,   // transparent cut-out, best
    p.image,                                // catalogue photo or texture render
    `images/buckets/${p.slug}.jpg`,         // legacy flat photo
  ].filter(Boolean);
  const found = candidates.find(has);
  // Site-root paths, with no leading slash. These are only ever consumed
  // from JavaScript, which resolves them through window.cpUrl — so they land
  // correctly whether the site is mounted at the domain root or inside a
  // subdirectory, and at either page depth.
  if (found) ART[p.slug] = found.replace(/\\/g, '/').replace(/^\//, '');
  else noArt.push(p.name);
}

fs.writeFileSync(path.join(ROOT, 'js', 'art-manifest.js'),
`// GENERATED by build/site.mjs — do not edit.
// The best available image for each product, resolved against the files that
// are actually on disk. A product missing from this map has no photograph and
// the page draws a typographic panel instead of requesting one and 404ing.
window.CLOUD_ART = ${JSON.stringify(ART, null, 1)};
`, 'utf8');

/* ---------- 2. product pages --------------------------------------------
   Every product gets a real URL. The template is product.html itself, so the
   markup can never drift from the one the site already ships; only the head
   and the asset paths are rewritten.

   Every path in the template gains a "../", because these pages are served
   one level down at /paints/<slug> where "css/main.css" would resolve to
   /paints/css/main.css.

   Relative, not root-relative. A leading slash fixes the depth problem and
   creates a worse one: it assumes the site is mounted at the domain root,
   which is true in production and false on a GitHub Pages project site or
   any staging folder — where every asset then misses by exactly the length
   of the prefix. */
const template = fs.readFileSync(path.join(ROOT, 'product.html'), 'utf8');

function oneLevelDown(html) {
  return html
    // bare relative -> ../
    .replace(/(\s(?:href|src|poster)=")(?!https?:|\/\/|\/|#|mailto:|tel:|data:|")/g, '$1../')
    // root-relative -> ../   (drops the slash rather than stacking on it)
    .replace(/(\s(?:href|src|poster)=")\/(?!\/)/g, '$1../')
    .replace(/(\surl\(")(?!https?:|\/|data:)/g, '$1../');
}

function productJsonLd(p, url, imgUrl) {
  const props = Object.entries(p.specs || {}).map(([name, value]) => ({
    '@type': 'PropertyValue', name, value: String(value),
  }));
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'Product',
    name: p.name,
    description: metaDescription(p.full || p.short || p.name, 300),
    sku: p.slug,
    category: p.cat_label,
    url,
    brand: { '@type': 'Brand', name: CO.brand },
    manufacturer: {
      '@type': 'Organization',
      name: CO.legal,
      address: {
        '@type': 'PostalAddress',
        streetAddress: CO.street,
        addressLocality: CO.area + ', ' + CO.city,
        addressCountry: CO.country,
      },
    },
    countryOfOrigin: { '@type': 'Country', name: 'Kenya' },
    ...(imgUrl ? { image: imgUrl } : {}),
    ...(props.length ? { additionalProperty: props } : {}),
    ...(p.sizes && p.sizes.length
      ? { hasVariant: p.sizes.map(s => ({ '@type': 'Product', name: `${p.name} ${s}`, sku: `${p.slug}-${s.toLowerCase()}` })) }
      : {}),
  };
  const crumbs = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: ORIGIN + '/' },
      { '@type': 'ListItem', position: 2, name: 'Products', item: ORIGIN + '/products' },
      { '@type': 'ListItem', position: 3, name: p.name, item: url },
    ],
  };
  return [ld, crumbs]
    .map(o => `<script type="application/ld+json">\n${JSON.stringify(o, null, 1)}\n</script>`)
    .join('\n');
}

fs.mkdirSync(path.join(ROOT, 'paints'), { recursive: true });
let written = 0;

for (const p of P) {
  const url = `${ORIGIN}/paints/${p.slug}`;
  const art = ART[p.slug];
  const imgUrl = art ? `${ORIGIN}/${art}` : '';
  /* Google shows about 60 characters of title. The category is genuinely
     useful there — "Weatherguard" alone says nothing to someone searching
     for exterior paint — so it stays whenever it fits, and is the first
     thing dropped when it does not. The brand is never dropped. */
  const title = [
    `${p.name} — ${p.cat_label} — Cloud Paints`,
    `${p.name} — Cloud Paints`,
    p.name,
  ].find(t => t.length <= 60) || `${p.name} — Cloud Paints`;
  const desc = metaDescription(p.short || p.full || `${p.name}. ${p.cat_label} from Cloud Paints, made in Nairobi.`);

  const head = [
    `<title>${esc(title)}</title>`,
    `<meta name="description" content="${esc(desc)}">`,
    `<link rel="canonical" href="${url}">`,
    `<meta property="og:site_name" content="Cloud Paints">`,
    `<meta property="og:type" content="product">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${esc(p.name)} — Cloud Paints">`,
    `<meta property="og:description" content="${esc(desc)}">`,
    imgUrl ? `<meta property="og:image" content="${imgUrl}">` : '',
    `<meta property="og:locale" content="en_KE">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${esc(p.name)} — Cloud Paints">`,
    `<meta name="twitter:description" content="${esc(desc)}">`,
    imgUrl ? `<meta name="twitter:image" content="${imgUrl}">` : '',
    `<meta name="theme-color" content="#d92843">`,
    productJsonLd(p, url, imgUrl),
    `<script>window.CP_PRODUCT_SLUG = ${JSON.stringify(p.slug)};</script>`,
  ].filter(Boolean).join('\n');

  let html = oneLevelDown(template);

  // Swap the template's placeholder head for this product's real one.
  html = html
    .replace(/<title>[\s\S]*?<\/title>\n?/, '')
    .replace(/<meta name="description"[^>]*>\n?/, '')
    .replace(/<meta property="og:site_name"[^>]*>\n?/, '')
    .replace(/<meta property="og:type"[^>]*>\n?/, '')
    .replace(/<meta property="og:image"[^>]*>\n?/, '')
    .replace(/<meta name="twitter:card"[^>]*>\n?/, '')
    .replace(/<meta name="theme-color"[^>]*>\n?/, '')
    .replace('</head>', head + '\n</head>');

  // The manifest has to be in scope before product-page.js runs.
  // base.js goes first — everything that builds a path in JavaScript has to
  // know where the site is mounted before it runs. The art manifest is
  // already in the template, so only insert what is missing.
  if (!html.includes('js/base.js')) {
    html = html.replace('<script src="../js/art-manifest.js"></script>',
                        '<script src="../js/base.js"></script>\n'
                      + '<script src="../js/art-manifest.js"></script>');
  }

  html = `<!-- GENERATED by build/site.mjs from product.html — do not edit by hand. -->\n` + html;
  fs.writeFileSync(path.join(ROOT, 'paints', `${p.slug}.html`), html, 'utf8');
  written++;
}

/* ---------- 3. sitemap --------------------------------------------------- */
const today = new Date().toISOString().slice(0, 10);
const PAGES = [
  ['/', 1.0], ['/products', 0.9], ['/colours', 0.9], ['/visualiser', 0.9],
  ['/textures', 0.8], ['/services', 0.8], ['/projects', 0.7], ['/inspiration', 0.7],
  ['/contact', 0.8], ['/about', 0.6], ['/discover', 0.6],
  ['/discover-signs-experts', 0.5], ['/discover-dual-protection', 0.5],
  ['/legal', 0.3],
];
const urls = [
  ...PAGES.map(([u, pr]) => ({ loc: ORIGIN + u, pr })),
  ...P.map(p => ({ loc: `${ORIGIN}/paints/${p.slug}`, pr: 0.8 })),
];
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'),
`<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by build/site.mjs — do not edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url><loc>${u.loc}</loc><lastmod>${today}</lastmod><priority>${u.pr.toFixed(1)}</priority></url>`).join('\n')}
</urlset>
`, 'utf8');

