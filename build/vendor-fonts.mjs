// ============================================================
// CLOUD PAINTS — self-host the web fonts
// ============================================================
// Pulls the Google Fonts stylesheet exactly as a modern browser
// would receive it, downloads every woff2 it names, and writes a
// local css/fonts.css that points at the copies.
//
//   node build/vendor-fonts.mjs
//
// Why bother:
//   · the zip has to work with no network at all
//   · fonts.googleapis.com is a third-party origin on every page
//     load, which a strict Content-Security-Policy would rather
//     not have to allow
//   · one fewer DNS lookup and connection before the first glyph
//
// Only the latin and latin-ext subsets are kept. Everything else
// Google offers for these families is for scripts the site does
// not set, and each one is another file in the package.
// ============================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'fonts');

const HREF = 'https://fonts.googleapis.com/css2'
  + '?family=Fraunces:opsz,wght@9..144,300;9..144,400;9..144,500;9..144,600;9..144,700'
  + '&family=Inter:wght@300;400;500;600;700;800'
  + '&family=Montserrat:ital,wght@0,700;0,800;0,900;1,700;1,800;1,900'
  + '&display=swap';

// Ask as Chrome, or Google serves the ancient truetype stylesheet.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
         + '(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const KEEP = new Set(['latin', 'latin-ext']);

const css = await (await fetch(HREF, { headers: { 'User-Agent': UA } })).text();
if (!css.includes('woff2')) {
  console.error('Google returned a stylesheet with no woff2 in it — aborting.');
  process.exit(1);
}

fs.mkdirSync(OUT_DIR, { recursive: true });

/* The stylesheet is a run of blocks, each preceded by a /* subset *\/ comment.
   Split on the comment so every @font-face knows which subset it belongs to. */
const blocks = css.split(/\/\*\s*([a-z-]+)\s*\*\//i).slice(1);
const out = [];
const downloads = new Map();
let kept = 0, skipped = 0;

for (let i = 0; i < blocks.length; i += 2) {
  const subset = blocks[i];
  const body = blocks[i + 1] || '';
  if (!KEEP.has(subset)) { skipped += (body.match(/@font-face/g) || []).length; continue; }

  const rewritten = body.replace(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g, (m, url) => {
    const family = (body.match(/font-family:\s*'([^']+)'/) || [, 'font'])[1].toLowerCase();
    let name = downloads.get(url);
    if (!name) {
      // Name the file for what it is, and keep Google's own hash so two
      // different faces can never collide on one filename.
      const hash = url.split('/').pop().replace(/\.woff2$/, '');
      name = `${family}-${subset}-${hash}.woff2`;
      downloads.set(url, name);
    }
    return `url(../fonts/${name})`;
  });
  out.push(`/* ${subset} */${rewritten}`);
  kept += (body.match(/@font-face/g) || []).length;
}

let bytes = 0;
for (const [url, name] of downloads) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) { console.error(`  ! ${name}: HTTP ${res.status}`); continue; }
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(path.join(OUT_DIR, name), buf);
  bytes += buf.length;
  process.stdout.write(`\r  downloaded ${downloads.size} faces…`);
}

fs.writeFileSync(path.join(ROOT, 'css', 'fonts.css'),
`/* GENERATED by build/vendor-fonts.mjs — do not edit.
   Fraunces, Inter and Montserrat, served from this site rather than from
   fonts.googleapis.com. Latin and latin-ext only; the unicode-range on each
   face means a browser still downloads just the subset it needs.
   Re-run the script to refresh. */

${out.join('\n')}
`, 'utf8');

console.log(`\n  ${kept} faces kept, ${skipped} skipped (other scripts)`);
console.log(`  ${downloads.size} woff2 files · ${(bytes / 1024).toFixed(0)} KB -> fonts/`);
console.log(`  stylesheet -> css/fonts.css`);
