window.getCloudColour = function (key) {
  if (!window.CLOUD_COLOURS) return null;
  var k = String(key).toLowerCase();
  return window.CLOUD_COLOURS.shades.find(function (s) {
    return s.slug === k || s.code.toLowerCase() === k;
  });
};
